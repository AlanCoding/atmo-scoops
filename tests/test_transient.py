from atmo_scoops.compressor import RealAir


def test_hardware_is_compiled_from_installed_inputs_and_fits_length():
    config=defaults();a=compile_hardware(*read_config(config))
    assert a['length_m']==317
    assert sum(g['depth_m'] for g in a['geometry'])+a['bay_m']==pytest.approx(317)
    assert all(g['gas_m3']>0 and g['envelope_m3']<=g['gross_m3'] for g in a['geometry'])
    config['design']['solar_area_m2']*=1.2
    b=compile_hardware(*read_config(config))
    assert b['geometry'][-1]['depth_m']<a['geometry'][-1]['depth_m']
    assert b['masses_kg']['solar']==pytest.approx(a['masses_kg']['solar']*1.2)
    assert b['masses_kg']['dive_compressors']==a['masses_kg']['dive_compressors']


@pytest.mark.parametrize('p,T,q',[(100.,400.,1000.),(1000.,500.,10000.),(5000.,350.,100000.)])
def test_real_gas_isentropic_work_matches_independent_bracketed_solver(p,T,q):
    expected=RealAir().compress(p,T,q,.75)['shaft_J_kg']
    assert properties().compression(T,p,q,Y,.75)==pytest.approx(expected,rel=2e-7)
    assert properties().compression(T,p,p)==0


def test_energy_inversion_and_real_liquid_phase_properties():
    p=properties()
    assert 77<p.boil[0]<78 and 89<p.boil[1]<91
    for T in (300,500,900):
        h,cp,R=p.at(T);m=42*Y
        assert p.temperature(42*(Y@h-R*T),m)==pytest.approx(T,abs=1e-8)
    w1,_=p.liquid_duty(350,Y,340,.15);w2,_=p.liquid_duty(350,Y,400,.15)
    assert w2>w1>0


def test_reject_unknown_input_and_impossible_fixed_geometry():
    x=defaults();x['design']['typo']=1
    with pytest.raises(ValueError):read_config(x)
    x=defaults();x['design']['length_diameter']=100
    with pytest.raises(ValueError):read_config(x)
    x=defaults();x['design']['solar_area_m2']=1e10
    with pytest.raises(ValueError):compile_hardware(*read_config(x))


def test_saved_reference_is_conservative_repeatable_and_not_proxy():
    # The complete expensive trajectory is regenerated by the documented report
    # command. This checks its recorded conservation/closure evidence in CI.
    import json
    from pathlib import Path
    r=json.loads(Path('results/transient/reference.json').read_text())
    assert r['audits']['forward_integrations']==1
    assert r['audits']['species_kg']<1e-4
    assert r['audits']['energy_MJ']<.01
    assert abs(r['closure']['thrust_relative'])<1e-4
    assert r['feasible'] and r['operating_payoff_days']>0
    assert r['delivered_payoff_days'] is None
    liquid=np.asarray(r['liquid_species_kg'])
    assert r['net_liquid_kg']==pytest.approx((liquid[-1]-liquid[0]).sum())
    assert all(e['hatch_allowed'] for e in r['events'])
    from atmo_scoops.transient.validate import check
    audit=check(r)
    assert audit['low_density_chamber_EOS_screen_passed']
    assert audit['max_compressor_work_relative_error']<1e-5


