"""Extract frozen v1 volumes and relocation moments; no cycle rerun."""
import gzip
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
r = json.load(gzip.open(ROOT / 'results/transient/plates/reference_validation/case_72.json.gz'))
l = json.loads((Path(__file__).parent / 'results.json').read_text())
h = r['hardware']
rows = l['components']
lines = ['# Frozen v1.0 volume register', '', 'Generated by `investigations/v1_layout/packaging_review.py` from case 72 and the existing axial register. Package volumes are envelopes, not solid material volumes. Axial overlaps mean side-by-side allocations, not proved collision-free solids.', '', '| Package | Envelope m³ | Allocated axial ranges, m |', '|---|---:|---|']
for cat in dict.fromkeys(c['category'] for c in rows if c.get('package_m3',0)):
 cs = [c for c in rows if c['category']==cat and c.get('package_m3',0)]
 spans=[]
 for c in sorted(cs,key=lambda c:c['x0_m']):
  if spans and abs(spans[-1][1]-c['x0_m'])<1e-6: spans[-1][1]=c['x1_m']
  else: spans.append([c['x0_m'],c['x1_m']])
 lines.append(f"| {cs[0]['name']} | {sum(c['package_m3'] for c in cs):,.1f} | "+'; '.join(f'{a:.2f}–{b:.2f}' for a,b in spans)+' |')
lines += ['', 'Do not add the aggregate `machines` allowance to these component rows: it is already decomposed here. Thruster pod envelopes are external in this layout. Margin is distributed mass, not a physical package.', '', '| Cooling volume | Gas m³ | Solid cooler m³ | Rack envelope m³ (includes gas gaps) | Chamber axial depth m |', '|---|---:|---:|---:|---:|']
for i,g in enumerate(h['geometry'],1):
 lines.append(f"| {i} | {g['gas_m3']:,.1f} | {g['solid_m3']:.2f} | {g['envelope_m3']:.2f} | {g['depth_m']:.3f} |")
lines += ['', 'Rack envelopes occupy the chambers; do not add them again to chamber volume. Vessel heads account for part of the axial depth; full-bore area times depth is not the internal gas volume.', '', '| Thruster centroid m | Dry CM m, fixed other mass | Dry CM m, proportional 25% contingency moved too |', '|---:|---:|---:|']
cs=[c for c in rows if c['category']=='thrusters']; m=sum(c['mass_kg'] for c in cs); x=sum(c['mass_kg']*c['centroid_m'] for c in cs)/m
for dest in [x,300.,317.]:
 dx=m*(dest-x)/l['dry_mass_kg']
 lines.append(f"| {dest:.2f} | {l['dry_CM_m']+dx:.2f} | {l['dry_CM_m']+1.25*dx:.2f} |")
lines += ['', 'Relocation only; no added cables, supports, booms, shielding or changed tank packaging. 317 m is an idealized centroid at the aft plane, not an installed pod geometry. These are not new payoff cases.']
(Path(__file__).parent/'VOLUME_REGISTER.md').write_text('\n'.join(lines)+'\n')
